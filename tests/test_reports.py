"""Report files: Markdown, JSON and PDF rendering."""
import io
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from deep_researcher import reports

MD = """# Remote work and productivity

_Question: does it help?_

## Executive summary

Overall the evidence is mixed [E-1111111111]. See https://example.org/a-very-long-url/that/keeps/going/and/going/x.

## Where the evidence disagrees

| Sub-question | Claim A | Claim B | Why they differ |
|---|---|---|---|
| sq1 | rises [E-1111111111] | falls [E-2222222222] | populations |

## Sources

- [E-1111111111] **A study** (2025-01-01) | papers | credibility 0.80 | https://example.org/a
"""


def test_markdown_to_pdf_renders_text_tables_and_urls():
    pytest.importorskip("xhtml2pdf")
    from pypdf import PdfReader

    data = reports.markdown_to_pdf(MD, title="Remote work and productivity")
    assert data[:5] == b"%PDF-"
    text = "".join(p.extract_text() for p in PdfReader(io.BytesIO(data)).pages)
    assert "Remote work and productivity" in text and "Why they differ" in text
    assert "E-1111111111" in text and "example.org/a" in text
    assert "Generated by Multi-Agent Deep Researcher" in text          # footer frame


def test_write_report_writes_md_json_and_pdf(tmp_path):
    md_path, json_path, pdf_path = reports.write_report("Does it help?", MD, {"title": "T"}, tmp_path)
    assert md_path.read_text() == MD and json_path.exists()
    assert pdf_path is not None and pdf_path.read_bytes()[:5] == b"%PDF-"
    assert md_path.stem == json_path.stem == pdf_path.stem


def test_write_report_survives_pdf_failure(tmp_path, monkeypatch):
    def boom(*a, **k):
        raise RuntimeError("no renderer")

    monkeypatch.setattr(reports, "markdown_to_pdf", boom)
    md_path, json_path, pdf_path = reports.write_report("Does it help?", MD, None, tmp_path)
    assert md_path.exists() and json_path is None and pdf_path is None
    assert reports.write_report("q" * 5, MD, None, tmp_path, pdf=False)[2] is None
