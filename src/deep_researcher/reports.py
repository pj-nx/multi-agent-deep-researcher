"""Writing finished reports to disk (shared by the CLI and the Gradio UI), including PDF rendering."""
from __future__ import annotations

import io
import json
import logging
import os
import re
import time
from pathlib import Path
from typing import Any

log = logging.getLogger(__name__)

PDF_CSS = """
@page { size: A4; margin: 2cm 2cm 2.2cm 2cm;
        @frame footer { -pdf-frame-content: pdf_footer; bottom: 1cm; height: 0.8cm;
                        margin-left: 2cm; margin-right: 2cm; } }
body { font-family: Helvetica; font-size: 10pt; line-height: 1.35; color: #111; }
h1 { font-size: 18pt; margin-bottom: 6pt; }
h2 { font-size: 14pt; margin-top: 16pt; border-bottom: 0.5pt solid #bbb; padding-bottom: 2pt; }
h3 { font-size: 11.5pt; margin-top: 12pt; }
p { margin: 0 0 6pt 0; }
li { margin-bottom: 2pt; }
table { width: 100%; font-size: 8.5pt; margin: 6pt 0 10pt 0; }
th { background-color: #eceff3; }
th, td { border: 0.5pt solid #999; padding: 3pt; vertical-align: top; }
a { color: #1a4fb3; text-decoration: none; }
code { font-family: Courier; font-size: 9pt; }
#pdf_footer { font-size: 8pt; color: #666; text-align: center; }
"""


def markdown_to_html(markdown_text: str) -> str:
    import markdown

    return markdown.markdown(markdown_text, extensions=["tables", "fenced_code", "sane_lists"])


def markdown_to_pdf(markdown_text: str, *, title: str | None = None) -> bytes:
    """Render a Markdown report to PDF bytes (pure Python: markdown -> HTML -> xhtml2pdf/reportlab)."""
    from xhtml2pdf import pisa

    body = markdown_to_html(markdown_text)
    footer = ("<div id='pdf_footer'>Generated by Multi-Agent Deep Researcher &middot; "
              "every [E-id] cites stored evidence</div>")
    html = (f"<html><head><meta charset='utf-8'><title>{(title or 'Research report')[:200]}</title>"
            f"<style>{PDF_CSS}</style></head><body>{body}{footer}</body></html>")
    out = io.BytesIO()
    status = pisa.CreatePDF(html, dest=out, encoding="utf-8")
    if status.err:
        raise RuntimeError(f"PDF rendering reported {status.err} error(s)")
    return out.getvalue()


def slugify(text: str, limit: int = 60) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower())[:limit].strip("-") or "report"


def reports_dir(default: str = "reports") -> Path:
    return Path(os.getenv("REPORTS_DIR") or default)


def write_report(question: str, markdown: str, report_json: dict[str, Any] | None,
                 out_dir: Path | None = None, *, pdf: bool = True) -> tuple[Path, Path | None, Path | None]:
    """Write ``<timestamp>-<slug>.md`` (+ ``.json``, + ``.pdf``) and return their paths.

    PDF rendering is best effort: a failure is logged and the ``.pdf`` path comes back as None.
    """
    out = out_dir or reports_dir()
    out.mkdir(parents=True, exist_ok=True)
    stem = f"{time.strftime('%Y%m%d-%H%M%S')}-{slugify(question)}"
    md_path = out / f"{stem}.md"
    md_path.write_text(markdown)
    json_path = None
    if report_json:
        json_path = out / f"{stem}.json"
        json_path.write_text(json.dumps(report_json, indent=2, default=str))
    pdf_path = None
    if pdf:
        try:
            pdf_path = out / f"{stem}.pdf"
            pdf_path.write_bytes(markdown_to_pdf(markdown, title=(report_json or {}).get("title")))
        except Exception as exc:  # noqa: BLE001 - the .md/.json are already safe; never fail the run on PDF
            log.warning("PDF rendering failed: %s", exc)
            pdf_path = None
    return md_path, json_path, pdf_path
